    /**
     * Import an example rule by key
     */
    public static function import_example($example_key) {
        $examples = self::get_examples();

        if (!isset($examples[$example_key])) {
            return false;
        }

        $example = $examples[$example_key];
        $rule_data = $example['rule'];
        $rule_data['id'] = '';  // Will be auto-generated

        return MMD_Discount_Rules::save_rule_set($rule_data);
    }
